-- BILINGUAL CONTENT SCHEMA — FA/EN i18n for app_content + membership_rules
-- ═══════════════════════════════════════════════════════════════════════════
-- Adds English columns to two tables that currently store Persian-only content:
--
--   1. app_content       — About / Terms / Privacy (CMS)
--   2. membership_rules  — Premium membership rules (versioned)
--
-- SAFETY (per spec):
--   • 100% idempotent (IF NOT EXISTS, UPDATE ... WHERE _en IS NULL)
--   • No DROP, no TRUNCATE, no DELETE of existing data
--   • Existing Persian columns (title, sections, body_markdown, summary) UNTOUCHED
--   • Re-running is safe: backfill only fills NULL English columns
--     (admin edits to English content are preserved on re-run)
--
-- Run against: Supabase PostgreSQL (DATABASE_URL)
-- ═══════════════════════════════════════════════════════════════════════════

-- ─── 1. app_content: add English columns ───────────────────────────────────
ALTER TABLE app_content ADD COLUMN IF NOT EXISTS title_en TEXT;
ALTER TABLE app_content ADD COLUMN IF NOT EXISTS sections_en JSONB NOT NULL DEFAULT '[]'::jsonb;

-- ─── 1b. app_content: backfill English content for existing rows ───────────
-- Only fills rows where title_en IS NULL (preserves admin edits on re-run).
-- Persian content (title, sections) is NEVER modified.

UPDATE app_content SET title_en = 'About Us',
  sections_en = '[
    {"heading":"AmirBTC Assistant","body":"AmirBTC Assistant is an intelligent financial markets assistant designed to provide fast information, smart analysis, and practical tools for market participants.\n\nThis platform aims to deliver market data, important news, smart analysis, and the tools financial market participants need in a fast, simple, and professional environment."},
    {"heading":"Features","body":"• Smart analysis of market news\n• Assessing the impact of news on the market\n• Quick access to important market information\n• Market management and tracking tools\n• Fast and modern user experience"},
    {"heading":"Mission","body":"Our goal is to build a professional tool that helps users make more informed decisions in the fast and complex environment of financial markets."}
  ]'::jsonb
WHERE id = 'about' AND title_en IS NULL;

