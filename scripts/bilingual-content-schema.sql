-- ─── 2. membership_rules: add English columns ─────────────────────────────
ALTER TABLE membership_rules ADD COLUMN IF NOT EXISTS title_en TEXT;
ALTER TABLE membership_rules ADD COLUMN IF NOT EXISTS body_markdown_en TEXT;
ALTER TABLE membership_rules ADD COLUMN IF NOT EXISTS summary_en TEXT;

-- ─── 2b. membership_rules: backfill English content for existing rows ──────
-- Only fills rows where title_en IS NULL (preserves admin edits on re-run).
-- Persian columns (title, body_markdown, summary) UNTOUCHED.

UPDATE membership_rules SET
  title_en = 'Premium Membership Rules — Version 1',
  body_markdown_en = E'# Premium Membership Rules\n\n## What is Premium?\n\nPremium membership is a special access tier that provides additional benefits in exchange for meeting membership conditions. Premium is not a paid subscription; it is a reward for users who are active in the AMIRBTC ecosystem and meet the membership conditions.\n\n## Premium Benefits\n\n- Higher quota for price alerts, AI chat, and other high-usage features\n- Access to the Premium Rewards Store (purchase with AB Token)\n- Access to the Profile Cosmetics Store (profile customization with AB Token)\n- Premium badge on profile\n- Priority access to new features and exclusive campaigns\n\n**Note:** Premium does not mean unlimited. For resource-intensive features, the Premium quota is higher than regular users but still limited.\n\n## Conditions for Maintaining Premium\n\n1. The user account must be active and accessible.\n2. Membership in the official AMIRBTC channel must be maintained.\n3. The current Exchange Requirement must be met.\n\n## Exchange Requirement\n\nAt any time, one exchange is defined as the "required exchange." The required exchange may change in the future. If it changes, a grace period is provided for you to comply.\n\n## Changes to Rules\n\nThese rules may be updated in the future. New users must accept the new version. Existing Premium users do not need to re-accept unless the changes are fundamental.\n\n## Acceptance of Rules\n\nBy accepting these rules, you confirm that you have read and accepted the rules and understand that Premium is a benefit conditional on meeting the requirements, not an absolute right.',
  summary_en = 'Complete Premium Membership Rules — conditions, benefits, limitations, and acceptance'
WHERE title_en IS NULL;

